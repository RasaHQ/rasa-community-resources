"""Record one synthetic caller through the real native Inspector voice path.

Caller speech is generated by Deepgram, not a human. Replies are recorded, not
played to a person. Playback acknowledgements follow the captured PCM duration.
This is a bounded integration observation, never a human speech-quality study.
"""
import argparse
import asyncio
import base64
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import signal
import socket
import subprocess
import sys
import time
import urllib.request
import wave

QUESTIONS = (
    "What is the available balance of checking A?",
    "Verify me.",
    "Transfer twelve U S dollars from checking A to savings A.",
    "Confirm transfer.",
)


def now():
    return datetime.now(timezone.utc).isoformat()


def wav(path, data):
    with wave.open(str(path), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(16000)
        output.writeframes(data)


async def synthesize(directory):
    from rasa.api.voice.tts.v1.deepgram import DeepgramTTS
    from rasa.api.voice.v1.audio import L16_16KHZ
    engine = DeepgramTTS.from_config_dict({"language_map": {"en": {
        "language": "en", "model": "aura-2-thalia-en"}}}, L16_16KHZ, "en")
    clips = []
    try:
        await asyncio.wait_for(engine.connect(), 25)
        for index, text in enumerate(QUESTIONS, 1):
            chunks = []
            async def collect():
                async for chunk in engine.synthesize(text):
                    chunks.append(chunk.data)
            await asyncio.wait_for(collect(), 45)
            data = b"".join(chunks)
            if not data:
                raise RuntimeError("caller_audio_empty")
            wav(directory / f"caller-{index}.wav", data)
            clips.append(data)
    finally:
        await asyncio.wait_for(engine.close_connection(), 10)
    return clips


async def conversation(directory, clips):
    import socketio
    client = socketio.AsyncClient(reconnection=False, logger=False, engineio_logger=False)
    confirmed = asyncio.Event()
    failed = asyncio.Event()
    playback_until = time.monotonic()
    ack_tasks = []
    received = bytearray()
    audio_chunks = 0
    with (directory / "socket-events.jsonl").open("a") as events:
        def retain(event, data):
            events.write(json.dumps({"at": now(), "event": event, "data": data}) + "\n")
            events.flush()
        async def ack(marker):
            await asyncio.sleep(max(0, playback_until - time.monotonic()))
            if client.connected:
                await client.emit("user_message", {"marker": marker})
                retain("playback_marker_ack_simulated", {"marker": marker})
        @client.on("session_confirm")
        async def session_confirm(data):
            retain("session_confirm", data)
            if data.get("sample_rate") != 16000:
                raise RuntimeError("unexpected_sample_rate")
            confirmed.set()
        @client.on("tracker")
        async def tracker(data):
            retain("tracker", data)
        @client.on("voice_error")
        async def voice_error(data):
            retain("voice_error", data)
            failed.set()
        @client.on("error")
        async def error(data):
            retain("error", data)
            failed.set()
        @client.on("bot_message")
        async def bot_message(data):
            nonlocal playback_until, audio_chunks
            retain("bot_message", data)
            value = json.loads(data) if isinstance(data, str) else data
            if not isinstance(value, dict):
                return
            if "audio" in value:
                pcm = base64.b64decode(value["audio"], validate=True)
                audio_chunks += 1
                received.extend(pcm)
                playback_until = max(time.monotonic(), playback_until) + len(pcm) / 32000
            if "marker" in value:
                ack_tasks.append(asyncio.create_task(ack(value["marker"])))
        try:
            await client.connect("http://127.0.0.1:5005", socketio_path="inspector.io",
                                 transports=["websocket"], wait_timeout=15)
            await client.emit("session_request", {"session_id": directory.name.removeprefix("rasa-"),
                                                   "is_voice": True})
            await asyncio.wait_for(confirmed.wait(), 15)
            await asyncio.sleep(3)
            for index, pcm in enumerate(clips, 1):
                if failed.is_set():
                    break
                retain("synthetic_caller_audio_intent", {"turn": index, "text": QUESTIONS[index - 1],
                                                         "sha256": hashlib.sha256(pcm).hexdigest()})
                # Same PCM16 / 16kHz wire format as the configured Inspector.
                for offset in range(0, len(pcm), 1024):
                    await client.emit("user_message", {"audio": base64.b64encode(pcm[offset:offset + 1024]).decode()})
                    await asyncio.sleep(len(pcm[offset:offset + 1024]) / 32000)
                # Browser microphones keep sending samples while the caller is quiet.
                # Preserve that PCM silence instead of leaving a 20-second wire gap.
                for _ in range(656):
                    await client.emit("user_message", {"audio": base64.b64encode(bytes(1024)).decode()})
                    await asyncio.sleep(.032)
                await asyncio.sleep(max(0, playback_until - time.monotonic()))
            if ack_tasks:
                await asyncio.gather(*ack_tasks, return_exceptions=True)
        finally:
            if client.connected:
                await client.disconnect()
            wav(directory / "agent-output.wav", bytes(received))
    return {"audio_chunks_received": audio_chunks, "agent_pcm_bytes": len(received),
            "voice_error_observed": failed.is_set()}


def require_free_port(port):
    """Refuse an already running server before generating paid caller audio."""
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", port))


def owned_server_ready(process, url):
    if process.poll() is not None:
        return False
    try:
        with urllib.request.urlopen(url, timeout=1) as response:
            return response.status == 200 and process.poll() is None
    except Exception:
        return False


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--state-dir", type=Path, required=True)
    parser.add_argument("--caller-clips", type=Path, help="Reuse four original synthetic WAVs without another TTS request")
    args = parser.parse_args()
    if not args.state_dir.is_absolute():
        parser.error("state-dir must be absolute")
    os.umask(0o077)
    args.state_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    if args.state_dir.is_symlink() or args.state_dir.stat().st_mode & 0o077:
        parser.error("state-dir must be a private real directory")
    fd = os.open(args.state_dir / "intent.json", os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    os.write(fd, json.dumps({"at": now(), "attempt_limit": 1, "caller": "Deepgram synthetic speech",
                            "scope": "local SOAP mock; four fixed voice turns; no real customer or bank"}).encode())
    os.fsync(fd)
    os.close(fd)
    def stop(*_):
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, stop)
    here = Path(__file__).resolve().parent
    result = {"at": now(), "scope": "Synthetic caller / headless native Inspector integration; no human playback judgment"}
    process = None
    log = (args.state_dir / "server.log").open("wb")
    try:
        require_free_port(5005)
        if args.caller_clips:
            clips = []
            for index in range(1, 5):
                original = args.caller_clips / f"caller-{index}.wav"
                with wave.open(str(original), "rb") as source:
                    if (source.getnchannels(), source.getsampwidth(), source.getframerate()) != (1, 2, 16000):
                        raise ValueError("caller_fixture_format_changed")
                    clips.append(source.readframes(source.getnframes()))
                (args.state_dir / original.name).write_bytes(original.read_bytes())
            result["caller_clip_source"] = str(args.caller_clips)
        else:
            clips = asyncio.run(synthesize(args.state_dir))
        environment = dict(os.environ, LITELLM_LOCAL_MODEL_COST_MAP="True", RASA_TELEMETRY_ENABLED="false",
                           DEMO_SEED="295185", SILVERLAKE_JOURNAL_DIR=str(args.state_dir / "journal"))
        process = subprocess.Popen([sys.executable, "run_demo.py", "--port", "5005"], cwd=here,
                                   env=environment, stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        ready = False
        deadline = time.monotonic() + 180
        while process.poll() is None and time.monotonic() < deadline:
            if owned_server_ready(process, "http://127.0.0.1:5005/"):
                ready = True
                break
            time.sleep(1)
        if not ready:
            raise RuntimeError("native_inspector_startup_failed")
        result.update(asyncio.run(conversation(args.state_dir, clips)))
        result["outcome"] = "OBSERVATION_RECORDED; inspect original events before claiming acceptance"
    except BaseException as error:
        result.update(outcome="RUN_FAILED", exception_type=type(error).__name__)
    finally:
        if process is not None and process.poll() is None:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=20)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
        log.close()
        result["completed_at"] = now()
        (args.state_dir / "result.json").write_text(json.dumps(result, indent=2) + "\n")
        print(json.dumps(result))
    return 1 if result.get("outcome") == "RUN_FAILED" else 0


if __name__ == "__main__":
    raise SystemExit(main())
