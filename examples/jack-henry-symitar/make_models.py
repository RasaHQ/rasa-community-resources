"""Generate vendor_models/ from the pinned Jack Henry Symitar files (`make models`).

The models carry interface facts only: field names, types, required fields,
nullability, formats, limits and allowed values, for the six operations this
example calls. Every description, example, title and vendor extension is
removed before generation, so no vendor prose reaches the repository. The
vendor files themselves stay in vendor-inputs/, which Git ignores.

Run it only with the exact pinned files (contract_inputs.PINS); any other bytes
are refused. `--check` regenerates into a temporary folder and fails if the
committed models differ, so a hand edit is caught.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile

import yaml

from contract_inputs import OPERATIONS, PINS, load_inputs

GENERATOR = "datamodel-code-generator==0.87.0"
OUTPUT = Path(__file__).resolve().parent / "vendor_models"
FAMILIES = ("accounts", "transactions", "loans", "transfers")
# Everything that is prose or metadata, not part of the interface. Removed only where it
# annotates a schema or an operation, never as a key of a name map or inside a literal value.
DROP = frozenset({"description", "example", "examples", "title", "externalDocs", "summary", "tags"})
# Maps whose keys are names (fields, media types, status codes, headers, links).
NAME_MAPS = frozenset({"properties", "patternProperties", "responses", "content", "headers", "links", "mapping",
                       "schemas"})
# Keywords whose value is a literal JSON value: kept exactly, never filtered.
LITERALS = frozenset({"enum", "default", "const"})
ARGUMENTS = (
    "--input-file-type", "openapi",
    "--openapi-scopes", "schemas", "paths",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-annotated",
    "--field-constraints",
    "--use-operation-id-as-name",
    # Exact models: a field the schema does not declare is not kept, so a field lost
    # in generation shows up in the round-trip test instead of hiding in model_extra.
    # (Not "forbid": the schema itself allows extra fields, and the OpenAPI validators
    # stay the authority on what a reply may carry.)
    "--extra-fields", "ignore",
    "--disable-timestamp",
    "--formatters", "black", "isort",
)


def _interface(node):
    """The schema without prose: names, types, required, nullable, enums and limits."""
    if isinstance(node, dict):
        kept = {}
        for key, value in node.items():
            if key in LITERALS:
                kept[key] = value
            elif key in NAME_MAPS and isinstance(value, dict):
                # Keys here are names, such as a field called "description": keep every one.
                kept[key] = {name: _interface(item) for name, item in value.items()}
            elif key not in DROP and not str(key).startswith("x-"):
                kept[key] = _interface(value)
        return kept
    if isinstance(node, list):
        return [_interface(value) for value in node]
    return node


def used_document(family: str, raw: bytes) -> dict:
    """The family's OpenAPI document cut down to the operations this example calls."""
    document = yaml.safe_load(raw)
    paths = {}
    for path, methods in document["paths"].items():
        for method, operation in methods.items():
            if isinstance(operation, dict) and operation.get("operationId") in OPERATIONS:
                kept = {key: operation[key] for key in ("operationId", "parameters", "requestBody", "responses")
                        if key in operation}
                paths.setdefault(path, {})[method] = kept
    # Keep the source document's own version line; replace everything else.
    trimmed = {key: document[key] for key in document if key not in ("paths", "components", "info", "servers",
                                                                      "security", "tags", "externalDocs")}
    trimmed["info"] = {"title": family, "version": document["info"]["version"]}
    trimmed["paths"] = _interface(paths)
    trimmed["components"] = {"schemas": _interface(document.get("components", {}).get("schemas", {}))}
    return trimmed


def header(family: str, raw: bytes) -> str:
    return (
        "# SPDX-License-Identifier: MIT\n"
        f"# Generated by `make models` with {GENERATOR}; do not edit by hand.\n"
        f"# Source: Jack Henry Symitar {family}.yaml, sha256 {hashlib.sha256(raw).hexdigest()}\n"
        "# Interface facts only (names, types, required, nullable, limits, allowed values);\n"
        "# descriptions and examples are removed before generation.\n"
    )


def generate(target: Path) -> None:
    inputs = load_inputs()
    for family in FAMILIES:
        if hashlib.sha256(inputs[family]).hexdigest() != PINS[family]:
            raise SystemExit(f"Refusing to generate: {family}.yaml is not the pinned file (see VENDOR-FILES.md).")
    target.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as folder:
        for family in FAMILIES:
            source = Path(folder) / f"{family}.json"
            source.write_text(json.dumps(used_document(family, inputs[family]), indent=1, sort_keys=True))
            output = Path(folder) / f"{family}.py"
            subprocess.run([str(Path(sys.executable).parent / "datamodel-codegen"), "--input", str(source),
                            "--output", str(output), *ARGUMENTS], check=True, capture_output=True)
            body = output.read_text()
            # The generator's own header names a temporary file; ours names the source.
            lines = body.splitlines(keepends=True)
            while lines and lines[0].startswith("#"):
                lines.pop(0)
            (target / f"{family}.py").write_text(header(family, inputs[family]) + "".join(lines))
    (target / "__init__.py").write_text(
        "# SPDX-License-Identifier: MIT\n"
        "\"\"\"Pydantic models generated from the pinned Jack Henry Symitar files (make models).\"\"\"\n")


def main(argv) -> int:
    if "--check" in argv:
        with tempfile.TemporaryDirectory() as folder:
            fresh = Path(folder) / "vendor_models"
            generate(fresh)
            stale = [path.name for path in sorted(fresh.iterdir())
                     if not (OUTPUT / path.name).is_file() or (OUTPUT / path.name).read_text() != path.read_text()]
        if stale:
            print("vendor_models/ differs from a fresh generation: " + ", ".join(stale) + ". Run make models.")
            return 1
        print("vendor_models/ matches the pinned files.")
        return 0
    generate(OUTPUT)
    print("Wrote vendor_models/ from the pinned files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
