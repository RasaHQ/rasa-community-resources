export const DICTS: Record<Lang, Record<TKey, string>> = { fr, en, de, es };

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let str: string = DICTS[lang][key] ?? DICTS.fr[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

export function formatNumber(lang: Lang, value: number): string {
  return value.toLocaleString(LOCALES[lang]);
}

export function formatNumberFr(value: number): string {
  return value.toLocaleString(LOCALES.fr);
}
